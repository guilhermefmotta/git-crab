mod commands;
mod git;

pub fn run() {
    tauri::Builder::default()
        .plugin(tauri_plugin_log::Builder::new().build())
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_shell::init())
        .invoke_handler(tauri::generate_handler![
            commands::forge::open_forge_window,
            commands::forge::detect_forge,
            commands::forge::save_forge_token,
            commands::forge::get_pull_requests,
            commands::forge::get_pipelines,
            commands::forge::get_pr_comments,
            commands::forge::post_pr_comment,
            commands::forge::trigger_pipeline,
            commands::forge::get_pipeline_jobs,
            commands::forge::retry_pipeline_job,
            commands::repo::open_repo,
            commands::repo::init_repo,
            commands::repo::clone_repo,
            commands::repo::get_recent_repos,
            commands::repo::add_recent_repo,
            commands::repo::remove_recent_repo,
            commands::repo::get_file_content,
            commands::repo::write_file_content,
            commands::repo::open_commit_window,
            commands::repo::open_file_diff_window,
            commands::repo::open_file_history_window,
            commands::repo::open_merge_window,
            commands::repo::open_path,
            commands::status::get_status,
            commands::status::stage_file,
            commands::status::unstage_file,
            commands::status::stage_all,
            commands::status::unstage_all,
            commands::status::stage_hunk,
            commands::status::unstage_hunk,
            commands::status::discard_changes,
            commands::status::ignore_file,
            commands::log::get_commits,
            commands::log::get_file_history,
            commands::rebase::get_rebase_commits,
            commands::rebase::start_interactive_rebase,
            commands::blame::get_blame,
            commands::blame::get_line_authors,
            commands::repo::open_blame_window,
            commands::repo::open_editor_window,
            commands::repo::list_repo_files,
            commands::repo::list_repo_tree,
            commands::repo::get_file_at_ref,
            commands::search::search_text,
            commands::log::get_reflog,
            commands::log::search_commits,
            commands::submodule::get_submodules,
            commands::diff::get_diff,
            commands::diff::get_line_changes,
            commands::commit::create_commit,
            commands::commit::amend_commit,
            commands::commit::undo_last_commit,
            commands::commit::cherry_pick,
            commands::commit::revert_commit,
            commands::commit::reset_to_commit,
            commands::branch::get_branches,
            commands::branch::create_branch,
            commands::branch::checkout_branch,
            commands::branch::delete_branch,
            commands::branch::rename_branch,
            commands::branch::rebase_branch,
            commands::merge::get_repo_status,
            commands::merge::get_conflict_content,
            commands::merge::resolve_conflict,
            commands::merge::abort_operation,
            commands::merge::complete_merge_commit,
            commands::merge::continue_operation,
            commands::merge::smart_checkout,
            commands::merge::do_merge,
            commands::remote::fetch_all,
            commands::remote::pull,
            commands::remote::push,
            commands::remote::get_remotes,
            commands::stash::get_stashes,
            commands::stash::create_stash,
            commands::stash::apply_stash,
            commands::stash::pop_stash,
            commands::stash::drop_stash,
            commands::tag::get_tags,
            commands::tag::create_tag,
            commands::tag::delete_tag,
        ])
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
